class Task(BaseModel):
    """
    Represents one section/task of the blog.
    """

    id: int

    title: str

    goal: str = Field(
        ...,
        description=(
            "One sentence describing what the reader should "
            "be able to do or understand after this section."
        ),
    )

    bullets: List[str] = Field(
        ...,
        min_length=3,
        max_length=6,
        description=(
            "3–6 concrete, non-overlapping subpoints "
            "to cover in this section."
        ),
    )

    target_words: int = Field(
        ...,
        description="Target word count for this section.",
    )

    section_type: Literal[
        "intro",
        "core",
        "examples",
        "checklist",
        "common_mistakes",
        "conclusion",
    ] = Field(
        ...,
        description="Type of the blog section.",
    )

    brief: str = Field(
        ...,
        description="What this section should cover.",
    )

    tags: List[str] = Field(
        default_factory=list,
        description="Important tags/topics for this section.",
    )

    requires_research: bool = Field(
        default=False,
        description="Whether this section requires fresh research.",
    )

    requires_citations: bool = Field(
        default=False,
        description="Whether outside-world claims need citations.",
    )

    requires_code: bool = Field(
        default=False,
        description="Whether this section must contain a code example.",
    )


class Plan(BaseModel):
    """
    Complete blog plan generated by the orchestrator.
    """

    blog_title: str

    audience: str = Field(
        description="Who this blog is made for.",
    )

    tone: str = Field(
        description=(
            "Writing tone, for example practical, crisp, "
            "technical, beginner-friendly, etc."
        ),
    )

    blog_kind: Literal[
        "tutorial",
        "news_roundup",
    ] = Field(
        default="tutorial",
        description="The overall type of the blog.",
    )

    constraints: List[str] = Field(
        default_factory=list,
        description="Important constraints that apply to the blog.",
    )

    tasks: List[Task] = Field(
    ...,
    min_length=MIN_SECTIONS,
    max_length=MAX_SECTIONS,
    description=(
        "Dynamically chosen blog sections/tasks. "
        "Must contain between 5 and 7 sections."
    ),
    )


class RouterDecision(BaseModel):
    """
    Decision produced by the routing node.
    """

    needs_research: bool

    mode: Literal[
        "closed_book",
        "hybrid",
        "open_book",
    ]

    queries: List[str] = Field(
        default_factory=list,
        max_length=10,
    )


class EvidenceItem(BaseModel):
    """
    One research source.
    """

    title: str

    url: str

    published_at: Optional[str] = None

    snippet: Optional[str] = None

    source: Optional[str] = None


class EvidencePack(BaseModel):
    """
    Collection of research sources.
    """

    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        max_length=MAX_EVIDENCE_SOURCES,
    )


