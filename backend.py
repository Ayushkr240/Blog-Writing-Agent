# 14. SEQUENTIAL WORKERS
# ============================================================

def workers_node(
    state: ChatState,
) -> dict:
    """
    Generate all five sections sequentially.

    This replaces LangGraph Send/fan-out so that five Gemini
    requests are NOT launched concurrently.

    The worker count remains exactly five.
    """

    plan = state.get(
        "plan"
    )

    if plan is None:

        raise ValueError(
            "Cannot run workers because plan is None."
        )

    tasks = plan.tasks

    if len(tasks) != WORKER_COUNT:

        raise ValueError(
            f"Expected {WORKER_COUNT} tasks, "
            f"got {len(tasks)}"
        )

    evidence = state.get(
        "evidence",
        []
    )[
        :MAX_EVIDENCE_SOURCES
    ]

    sections = []

    for task in tasks:

        payload = _build_worker_payload(
            plan=plan,
            task=task,
            topic=state["topic"],
            mode=state.get(
                "mode",
                "closed_book",
            ),
            evidence=evidence,
        )

        task_id, section_md = (
            _generate_worker_section(
                payload
            )
        )

        sections.append(
            (
                task_id,
                section_md,
            )
        )

    return {
        "sections": sections
    }


# ============================================================
# 15. FILENAME SANITIZATION
# ============================================================

def safe_filename(title: str) -> str:

    filename = re.sub(
        r'[<>:"/\\|?*]',
        "",
        title,
    )

    filename = filename.strip()

    if not filename:

        filename = "blog"

    return filename


# ============================================================
# 16. REDUCER
# ============================================================

def reducer(
    state: ChatState,
) -> dict:
    """
    Combine the five worker sections in task-ID order and
    create the final Markdown file.
    """

    plan = state.get(
        "plan"
    )

    if plan is None:

        raise ValueError(
            "Cannot reduce because plan is None."
        )

    sections = state.get(
        "sections",
        []
    )

    ordered_sections = [
        markdown
        for _, markdown
        in sorted(
            sections,
            key=lambda item: item[0],
        )
    ]

    body = "\n\n".join(
        ordered_sections
    ).strip()

    final_md = (
        f"# {plan.blog_title}\n\n"
        f"{body}\n"
    )

    filename = (
        f"{safe_filename(plan.blog_title)}.md"
    )

    Path(filename).write_text(
        final_md,
        encoding="utf-8",
    )

    return {
        "final_md": final_md
    }


