def _build_worker_payload(
    plan: Plan,
    task: Task,
    topic: str,
    mode: str,
    evidence: List[EvidenceItem],
) -> dict:

    return {
        "plan": plan.model_dump(),
        "topic": topic,
        "task": task.model_dump(),
        "mode": mode,
        "evidence": [
            item.model_dump()
            for item in evidence[
                :MAX_EVIDENCE_SOURCES
            ]
        ],
    }


def _generate_worker_section(
    payload: dict,
) -> tuple[int, str]:

    task = Task(
        **payload["task"]
    )

    plan = Plan(
        **payload["plan"]
    )

    evidence = [
        EvidenceItem(**item)
        for item in payload.get(
            "evidence",
            []
        )[
            :MAX_EVIDENCE_SOURCES
        ]
    ]

    topic = payload["topic"]

    mode = payload.get(
        "mode",
        "closed_book",
    )

    bullets_text = "\n".join(
        f"- {bullet}"
        for bullet in task.bullets
    )

    evidence_lines = []

    for item in evidence:

        evidence_lines.append(
            (
                f"- Title: {item.title}\n"
                f"  URL: {item.url}\n"
                f"  Date: "
                f"{item.published_at or 'unknown'}\n"
                f"  Snippet: "
                f"{item.snippet or ''}"
            )
        )

    evidence_text = "\n".join(
        evidence_lines
    )

    response = llm.invoke(
        [
            SystemMessage(
                content=WORKER_SYSTEM
            ),
            HumanMessage(
                content=(
                    f"Blog title:\n"
                    f"{plan.blog_title}\n\n"

                    f"Audience:\n"
                    f"{plan.audience}\n\n"

                    f"Tone:\n"
                    f"{plan.tone}\n\n"

                    f"Blog kind:\n"
                    f"{plan.blog_kind}\n\n"

                    f"Constraints:\n"
                    f"{plan.constraints}\n\n"

                    f"Topic:\n"
                    f"{topic}\n\n"

                    f"Mode:\n"
                    f"{mode}\n\n"

                    f"Section title:\n"
                    f"{task.title}\n\n"

                    f"Section type:\n"
                    f"{task.section_type}\n\n"

                    f"Goal:\n"
                    f"{task.goal}\n\n"

                    f"Brief:\n"
                    f"{task.brief}\n\n"

                    f"Target words:\n"
                    f"{task.target_words}\n\n"

                    f"Tags:\n"
                    f"{task.tags}\n\n"

                    f"requires_research:\n"
                    f"{task.requires_research}\n\n"

                    f"requires_citations:\n"
                    f"{task.requires_citations}\n\n"

                    f"requires_code:\n"
                    f"{task.requires_code}\n\n"

                    f"Bullets:\n"
                    f"{bullets_text}\n\n"

                    "Evidence "
                    "(ONLY use these URLs when citing):\n"
                    f"{evidence_text}"
                )
            ),
        ]
    )

    # IMPORTANT GEMINI FIX:
    # response.content may be a list.
    section_md = _extract_response_text(
        response
    )

    if not section_md:

        raise ValueError(
            f"Worker {task.id} received an empty "
            "response from Gemini."
        )

    return (
        task.id,
        section_md,
    )


