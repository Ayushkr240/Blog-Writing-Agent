def validate_plan(plan: Plan) -> Plan:
    """
    Validate the orchestrator's dynamic blog plan.

    The orchestrator may choose 5, 6, or 7 sections,
    but never fewer than 5 or more than 7.
    """

    task_count = len(plan.tasks)

    if not (
        MIN_SECTIONS
        <= task_count
        <= MAX_SECTIONS
    ):

        raise ValueError(
            f"Plan must contain between "
            f"{MIN_SECTIONS} and {MAX_SECTIONS} sections, "
            f"got {task_count}"
        )

    task_ids = [
        task.id
        for task in plan.tasks
    ]

    if len(set(task_ids)) != len(task_ids):

        raise ValueError(
            "Task IDs must be unique."
        )

    expected_ids = list(
        range(
            1,
            task_count + 1,
        )
    )

    if sorted(task_ids) != expected_ids:

        raise ValueError(
            "Task IDs must be sequential starting from 1. "
            f"Expected {expected_ids}, got {sorted(task_ids)}"
        )

    common_mistakes_count = sum(
        task.section_type
        == "common_mistakes"
        for task in plan.tasks
    )

    if common_mistakes_count != 1:

        raise ValueError(
            "Plan must contain exactly one "
            "'common_mistakes' section."
        )

    return plan


def orchestrator_node(
    state: ChatState,
) -> dict:

    evidence = state.get(
        "evidence",
        []
    )

    # Never pass more than the selected 12 sources.
    evidence_for_prompt = [
        item.model_dump()
        for item in evidence[
            :MAX_EVIDENCE_SOURCES
        ]
    ]

    mode = state.get(
        "mode",
        "closed_book",
    )

    plan = _invoke_structured(
        Plan,
        [
            SystemMessage(
                content=ORCH_MESSAGE
            ),
            HumanMessage(
                content=(
                    f"Topic:\n"
                    f"{state['topic']}\n\n"

                    f"Mode:\n"
                    f"{mode}\n\n"

                    "Evidence "
                    "(ONLY use for fresh claims; "
                    "may be empty):\n"
                    f"{evidence_for_prompt}"
                )
            ),
        ],
    )

    plan = validate_plan(plan)

    return {
        "plan": plan
    }


