def _initial_state(
    topic: str,
) -> ChatState:

    return {
        "topic": topic,

        "mode": "",

        "needs_research": False,

        "queries": [],

        "evidence": [],

        "plan": None,

        "sections": [],

        "final_md": "",
    }


# ============================================================
# 19. NORMAL RUNNER
# ============================================================

def run(topic: str):

    topic = str(
        topic
    ).strip()

    if not topic:

        raise ValueError(
            "Topic cannot be empty."
        )

    return app.invoke(
        _initial_state(topic)
    )


# ============================================================
# 20. STREAMING RUNNER
# ============================================================

def run_stream(topic: str):
    """
    Stream LangGraph node updates.

    The graph itself is streamed at node level.
    The five worker LLM calls are intentionally sequential
    inside the workers node.
    """

    topic = str(
        topic
    ).strip()

    if not topic:

        raise ValueError(
            "Topic cannot be empty."
        )

    initial_state = _initial_state(
        topic
    )

    for event in app.stream(
        initial_state,
        stream_mode="updates",
    ):
        yield event


