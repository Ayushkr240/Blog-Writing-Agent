class WorkerState(TypedDict):
    """
    State received by one dynamically created worker branch.

    Each worker receives exactly one planned Task, while the
    parent ChatState keeps the shared blog-generation state.
    """

    plan: Plan

    task: Task

    topic: str

    mode: str

    evidence: List[EvidenceItem]


def worker_node(
    state: WorkerState,
) -> dict:
    """
    Generate exactly one blog section.

    LangGraph invokes this node once for every Task emitted by
    the fan-out function. The invocations can run concurrently.
    """

    payload = _build_worker_payload(
        plan=state["plan"],
        task=state["task"],
        topic=state["topic"],
        mode=state.get(
            "mode",
            "closed_book",
        ),
        evidence=state.get(
            "evidence",
            [],
        ),
    )

    task_id, section_md = _generate_worker_section(
        payload
    )

    return {
        "sections": [
            (
                task_id,
                section_md,
            )
        ]
    }


def fan_out_workers(
    state: ChatState,
) -> List[Send]:

    plan = state.get("plan")

    if plan is None:
        raise ValueError(
            "Cannot fan out workers because plan is None."
        )

    evidence = state.get(
        "evidence",
        [],
    )[:MAX_EVIDENCE_SOURCES]

    topic = state.get(
        "topic",
        "",
    )

    mode = state.get(
        "mode",
        "closed_book",
    )

    sends = []

    for task in plan.tasks:

        sends.append(
            Send(
                "worker",
                {
                    "plan": plan,
                    "task": task,
                    "topic": topic,
                    "mode": mode,
                    "evidence": evidence,
                },
            )
        )

    return sends

