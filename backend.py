# 16. REDUCER
# ============================================================

def reducer(
    state: ChatState,
) -> dict:
    """
    Combine all dynamically generated worker sections in
    task-ID order and return the final Markdown content.
    """

    plan = state.get(
        "plan"
    )

    if plan is None:

        raise ValueError(
            "Cannot reduce because plan is None."
        )

    sections = state.get(
        "sections",
        []
    )

    ordered_sections = [
        markdown
        for _, markdown
        in sorted(
            sections,
            key=lambda item: item[0],
        )
    ]

    body = "\n\n".join(
        ordered_sections
    ).strip()

    final_md = (
        f"# {plan.blog_title}\n\n"
        f"{body}\n"
    )

    return {
        "final_md": final_md
    }


