# 9. DETERMINISTIC SOURCE RANKING
# ============================================================

def _domain_matches(
    domain: str,
    allowed_domain: str,
) -> bool:
    """
    Return True only when the domain is exactly the allowed
    domain or is a legitimate subdomain of it.

    Examples:

    github.com            -> True
    docs.github.com       -> True
    notgithub.com         -> False
    github.com.evil.com   -> False
    """

    domain = domain.lower().strip(".")
    allowed_domain = (
        allowed_domain
        .lower()
        .strip(".")
    )

    return (
        domain == allowed_domain
        or domain.endswith(
            "." + allowed_domain
        )
    )


def _source_authority_score(item: dict) -> int:
    """
    Lightweight deterministic authority scoring.

    This happens BEFORE the evidence synthesizer, so only the
    best ~10–15 sources ever reach the LLM.
    """

    url = item.get(
        "url",
        "",
    )

    domain = _domain_from_url(
        url
    )

    score = 0

    high_authority_domains = (
        ".gov",
        ".edu",
        "github.com",
        "arxiv.org",
        "openai.com",
        "developers.google.com",
        "ai.google.dev",
        "cloud.google.com",
        "python.org",
        "pytorch.org",
        "tensorflow.org",
        "microsoft.com",
        "aws.amazon.com",
        "anthropic.com",
        "meta.com",
        "developer.mozilla.org",
    )

    reputable_domains = (
        "reuters.com",
        "apnews.com",
        "bbc.com",
        "nytimes.com",
        "techcrunch.com",
        "theverge.com",
        "wired.com",
        "nature.com",
        "arstechnica.com",
    )

    # --------------------------------------------------------
    # High-authority sources
    # --------------------------------------------------------

    if any(
        (
            domain.endswith(suffix)
            if suffix.startswith(".")
            else _domain_matches(
                domain,
                suffix,
            )
        )
        for suffix in high_authority_domains
    ):
        score += 8

    # --------------------------------------------------------
    # Reputable sources
    # --------------------------------------------------------

    if any(
        _domain_matches(
            domain,
            suffix,
        )
        for suffix in reputable_domains
    ):
        score += 5

    # --------------------------------------------------------
    # Freshness
    # --------------------------------------------------------

    if item.get(
        "published_at"
    ):
        score += 1

    # --------------------------------------------------------
    # Useful snippet
    # --------------------------------------------------------

    if item.get(
        "snippet"
    ):
        score += 2

    return score

def _rank_and_select_sources(
    raw_results: List[dict],
    topic: str,
    queries: List[str],
) -> List[dict]:
    """
    Deduplicate, score and select at most 8 sources.

    The full raw Tavily result set is NEVER passed to Gemini.
    """

    query_terms = set(
        re.findall(
            r"\b[a-zA-Z0-9][a-zA-Z0-9_-]{2,}\b",
            " ".join(
                [topic] + queries
            ).lower(),
        )
    )

    unique = {}

    for item in raw_results:

        url = item.get("url", "").strip()

        if not url:
            continue

        if url not in unique:
            unique[url] = item
            continue

        # Keep the richer duplicate.
        old = unique[url]

        if len(
            item.get("snippet", "")
        ) > len(
            old.get("snippet", "")
        ):
            unique[url] = item

    scored = []

    for item in unique.values():

        title = item.get(
            "title",
            "",
        ).lower()

        snippet = item.get(
            "snippet",
            "",
        ).lower()

        text = f"{title} {snippet}"

        overlap = sum(
            1
            for term in query_terms
            if term in text
        )

        score = (
            overlap * 2
            + _source_authority_score(item)
        )

        scored.append(
            (
                score,
                item,
            )
        )

    scored.sort(
        key=lambda pair: (
            pair[0],
            len(
                pair[1].get(
                    "snippet",
                    "",
                )
            ),
        ),
        reverse=True,
    )

    return [
        item
        for _, item in scored[
            :MAX_EVIDENCE_SOURCES
        ]
    ]


