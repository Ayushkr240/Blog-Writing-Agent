def _extract_response_text(response) -> str:
    """
    Normalize LangChain/Gemini response content into plain text.

    Gemini may expose response.content as:
    - a string
    - a list of content blocks
    - a list of strings
    - a list of dictionaries containing text
    - nested content structures
    """

    content = getattr(response, "content", response)

    if isinstance(content, str):
        return content.strip()

    if isinstance(content, list):

        parts: List[str] = []

        def collect(item) -> None:

            if isinstance(item, str):
                if item.strip():
                    parts.append(item)
                return

            if isinstance(item, dict):

                text_value = item.get("text")

                if isinstance(text_value, str):
                    if text_value.strip():
                        parts.append(text_value)
                    return

                nested = item.get("content")

                if isinstance(nested, str):
                    if nested.strip():
                        parts.append(nested)
                    return

                if isinstance(nested, list):
                    for nested_item in nested:
                        collect(nested_item)

                return

        for item in content:
            collect(item)

        return "\n".join(parts).strip()

    return str(content).strip()


def _invoke_structured(schema, messages):
    """
    Invoke Gemini using LangChain structured output.

    Gemini's structured-output path returns a Pydantic object.
    This helper also provides a useful error if the provider
    returns something unexpected.
    """

    structured_llm = llm.with_structured_output(
        schema
    )

    result = structured_llm.invoke(messages)

    if isinstance(result, schema):
        return result

    try:
        return schema.model_validate(result)
    except Exception as exc:
        raise ValueError(
            f"Gemini returned an unexpected structured-output "
            f"format for {schema.__name__}: {result!r}"
        ) from exc


