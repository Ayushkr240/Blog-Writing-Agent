# 8. PDF EXPORT
# ============================================================

def export_pdf(
    markdown_content: str,
) -> tuple[bytes, str]:
    """
    Convert the Markdown blog into a PDF document.

    Returns:
        tuple[bytes, str]:
            - PDF file as bytes
            - Suggested filename
    """

    if not markdown_content or not markdown_content.strip():
        raise ValueError(
            "Markdown content cannot be empty."
        )

    try:
        from xml.sax.saxutils import escape

        from reportlab.lib.enums import TA_LEFT
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import (
            ParagraphStyle,
            getSampleStyleSheet,
        )
        from reportlab.lib.units import inch
        from reportlab.platypus import (
            HRFlowable,
            ListFlowable,
            ListItem,
            Paragraph,
            Preformatted,
            SimpleDocTemplate,
            Spacer,
        )

    except ImportError as exc:
        raise ImportError(
            "The 'reportlab' package is required "
            "for PDF export. Install it with: "
            "pip install reportlab"
        ) from exc

    # --------------------------------------------------------
    # Create PDF in memory
    # --------------------------------------------------------

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
        title=extract_blog_title(
            markdown_content
        ),
    )

    # --------------------------------------------------------
    # Styles
    # --------------------------------------------------------

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "BlogTitle",
        parent=styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=24,
        leading=29,
        alignment=TA_LEFT,
        spaceAfter=18,
    )

    h2_style = ParagraphStyle(
        "BlogHeading2",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=17,
        leading=21,
        spaceBefore=14,
        spaceAfter=8,
    )

    h3_style = ParagraphStyle(
        "BlogHeading3",
        parent=styles["Heading3"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        spaceBefore=12,
        spaceAfter=6,
    )

    h4_style = ParagraphStyle(
        "BlogHeading4",
        parent=styles["Heading4"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=15,
        spaceBefore=10,
        spaceAfter=5,
    )

    body_style = ParagraphStyle(
        "BlogBody",
        parent=styles["BodyText"],
        fontName="Helvetica",
        fontSize=10.5,
        leading=16,
        spaceAfter=8,
    )

    bullet_style = ParagraphStyle(
        "BlogBullet",
        parent=body_style,
        leftIndent=18,
        firstLineIndent=0,
        spaceAfter=4,
    )

    quote_style = ParagraphStyle(
        "BlogQuote",
        parent=body_style,
        leftIndent=24,
        rightIndent=12,
        fontName="Helvetica-Oblique",
        spaceBefore=5,
        spaceAfter=8,
    )

    code_style = ParagraphStyle(
        "BlogCode",
        parent=styles["Code"],
        fontName="Courier",
        fontSize=8.5,
        leading=12,
        leftIndent=8,
        rightIndent=8,
        spaceBefore=6,
        spaceAfter=8,
    )

    # --------------------------------------------------------
    # Inline Markdown → ReportLab markup
    # --------------------------------------------------------

    def format_inline(text: str) -> str:
        """
        Convert basic Markdown inline formatting into
        ReportLab-compatible XML markup.
        """

        # Escape XML-sensitive characters first.
        text = escape(text)

        # Inline code.
        text = re.sub(
            r"`([^`]+)`",
            r'<font name="Courier">\1</font>',
            text,
        )

        # Bold.
        text = re.sub(
            r"\*\*(.*?)\*\*",
            r"<b>\1</b>",
            text,
        )

        text = re.sub(
            r"__(.*?)__",
            r"<b>\1</b>",
            text,
        )

        # Italic.
        text = re.sub(
            r"\*(.*?)\*",
            r"<i>\1</i>",
            text,
        )

        text = re.sub(
            r"_(.*?)_",
            r"<i>\1</i>",
            text,
        )

        # Markdown links.
        text = re.sub(
            r"\[([^\]]+)\]\(([^)]+)\)",
            r'<link href="\2" color="blue">\1</link>',
            text,
        )

        return text

    # --------------------------------------------------------
    # Build PDF story
    # --------------------------------------------------------

    story = []

    lines = markdown_content.splitlines()

    inside_code_block = False
    code_lines = []

    bullet_items = []
    numbered_items = []

    def flush_bullets():
        if not bullet_items:
            return

        items = [
            ListItem(
                Paragraph(
                    format_inline(item),
                    bullet_style,
                )
            )
            for item in bullet_items
        ]

        story.append(
            ListFlowable(
                items,
                bulletType="bullet",
                leftIndent=18,
                bulletFontName="Helvetica",
                bulletFontSize=8,
            )
        )

        story.append(
            Spacer(1, 5)
        )

        bullet_items.clear()

    def flush_numbered():
        if not numbered_items:
            return

        items = [
            ListItem(
                Paragraph(
                    format_inline(item),
                    bullet_style,
                )
            )
            for item in numbered_items
        ]

        story.append(
            ListFlowable(
                items,
                bulletType="1",
                start="1",
                leftIndent=22,
            )
        )

        story.append(
            Spacer(1, 5)
        )

        numbered_items.clear()

    for line in lines:

        stripped = line.strip()

        # ----------------------------------------------------
        # Code block
        # ----------------------------------------------------

        if stripped.startswith("```"):

            if not inside_code_block:

                flush_bullets()
                flush_numbered()

                inside_code_block = True
                code_lines = []

            else:

                inside_code_block = False

                code_text = "\n".join(
                    code_lines
                )

                story.append(
                    Preformatted(
                        code_text,
                        code_style,
                    )
                )

                code_lines = []

            continue

        if inside_code_block:

            code_lines.append(line)
            continue

        # ----------------------------------------------------
        # Empty line
        # ----------------------------------------------------

        if not stripped:

            flush_bullets()
            flush_numbered()

            story.append(
                Spacer(1, 3)
            )

            continue

        # ----------------------------------------------------
        # Bullet
        # ----------------------------------------------------

        bullet_match = re.match(
            r"^[-*+]\s+(.+)",
            stripped,
        )

        if bullet_match:

            flush_numbered()

            bullet_items.append(
                bullet_match.group(1)
            )

            continue

        # ----------------------------------------------------
        # Numbered list
        # ----------------------------------------------------

        numbered_match = re.match(
            r"^\d+\.\s+(.+)",
            stripped,
        )

        if numbered_match:

            flush_bullets()

            numbered_items.append(
                numbered_match.group(1)
            )

            continue

        # ----------------------------------------------------
        # Everything below this point is not a list.
        # Flush any pending list items first.
        # ----------------------------------------------------

        flush_bullets()
        flush_numbered()

        # ----------------------------------------------------
        # Heading 1
        # ----------------------------------------------------

        if re.match(
            r"^#\s+",
            stripped,
        ):

            heading = re.sub(
                r"^#\s+",
                "",
                stripped,
            )

            story.append(
                Paragraph(
                    format_inline(heading),
                    title_style,
                )
            )

            continue

        # ----------------------------------------------------
        # Heading 2
        # ----------------------------------------------------

        if re.match(
            r"^##\s+",
            stripped,
        ):

            heading = re.sub(
                r"^##\s+",
                "",
                stripped,
            )

            story.append(
                Paragraph(
                    format_inline(heading),
                    h2_style,
                )
            )

            continue

        # ----------------------------------------------------
        # Heading 3
        # ----------------------------------------------------

        if re.match(
            r"^###\s+",
            stripped,
        ):

            heading = re.sub(
                r"^###\s+",
                "",
                stripped,
            )

            story.append(
                Paragraph(
                    format_inline(heading),
                    h3_style,
                )
            )

            continue

        # ----------------------------------------------------
        # Heading 4–6
        # ----------------------------------------------------

        heading_match = re.match(
            r"^(#{4,6})\s+(.+)",
            stripped,
        )

        if heading_match:

            heading = heading_match.group(2)

            story.append(
                Paragraph(
                    format_inline(heading),
                    h4_style,
                )
            )

            continue

        # ----------------------------------------------------
        # Blockquote
        # ----------------------------------------------------

        quote_match = re.match(
            r"^>\s?(.*)",
            stripped,
        )

        if quote_match:

            story.append(
                Paragraph(
                    format_inline(
                        quote_match.group(1)
                    ),
                    quote_style,
                )
            )

            continue

        # ----------------------------------------------------
        # Horizontal rule
        # ----------------------------------------------------

        if re.match(
            r"^([-*_])(?:\s*\1){2,}$",
            stripped,
        ):

            story.append(
                Spacer(1, 5)
            )

            story.append(
                HRFlowable(
                    width="100%",
                    thickness=0.7,
                    spaceBefore=4,
                    spaceAfter=8,
                )
            )

            continue

        # ----------------------------------------------------
        # Normal paragraph
        # ----------------------------------------------------

        story.append(
            Paragraph(
                format_inline(stripped),
                body_style,
            )
        )

    # --------------------------------------------------------
    # Flush remaining lists
    # --------------------------------------------------------

    flush_bullets()
    flush_numbered()

    # --------------------------------------------------------
    # Build PDF
    # --------------------------------------------------------

    document.build(story)

    buffer.seek(0)

    filename = build_export_filename(
        markdown_content,
        "pdf",
    )

    return (
        buffer.getvalue(),
        filename,
    )