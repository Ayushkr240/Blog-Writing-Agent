# 6. HTML EXPORT
# ============================================================

def export_html(
    markdown_content: str,
) -> tuple[str, str]:
    """
    Convert the Markdown blog into a complete HTML document.

    The resulting HTML includes:

        - UTF-8 character encoding
        - Responsive layout
        - Blog typography
        - Styled code blocks
        - Styled blockquotes
        - Lists
        - Links

    Markdown is converted using the 'markdown' Python package.
    """

    if not markdown_content or not markdown_content.strip():
        raise ValueError(
            "Markdown content cannot be empty."
        )

    try:
        import markdown
    except ImportError as exc:
        raise ImportError(
            "The 'markdown' package is required "
            "for HTML export. Install it with: "
            "pip install markdown"
        ) from exc

    # --------------------------------------------------------
    # Convert Markdown → HTML body.
    # --------------------------------------------------------

    html_body = markdown.markdown(
        markdown_content,
        extensions=[
            "fenced_code",
            "tables",
            "nl2br",
        ],
    )

    # --------------------------------------------------------
    # Create a complete standalone HTML document.
    # --------------------------------------------------------

    title = extract_blog_title(
        markdown_content
    )

    escaped_title = (
        title.replace(
            "&",
            "&amp;",
        )
        .replace(
            "<",
            "&lt;",
        )
        .replace(
            ">",
            "&gt;",
        )
        .replace(
            '"',
            "&quot;",
        )
    )

    html_document = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta
        name="viewport"
        content="width=device-width, initial-scale=1.0"
    >
    <title>{escaped_title}</title>

    <style>
        body {{
            max-width: 900px;
            margin: 0 auto;
            padding: 40px 24px;
            font-family:
                -apple-system,
                BlinkMacSystemFont,
                "Segoe UI",
                sans-serif;
            line-height: 1.7;
            color: #222;
            background: #fff;
        }}

        h1 {{
            font-size: 2.4rem;
            line-height: 1.2;
            margin-bottom: 1.5rem;
        }}

        h2 {{
            margin-top: 2.5rem;
        }}

        h3 {{
            margin-top: 2rem;
        }}

        p {{
            margin: 1rem 0;
        }}

        ul,
        ol {{
            padding-left: 2rem;
        }}

        li {{
            margin: 0.4rem 0;
        }}

        blockquote {{
            margin: 1.5rem 0;
            padding: 0.8rem 1.2rem;
            border-left: 4px solid #999;
            background: #f5f5f5;
        }}

        pre {{
            overflow-x: auto;
            padding: 1rem;
            border-radius: 8px;
            background: #f4f4f4;
        }}

        code {{
            font-family:
                "Cascadia Code",
                "Fira Code",
                Consolas,
                monospace;
        }}

        :not(pre) > code {{
            padding: 0.15rem 0.35rem;
            border-radius: 4px;
            background: #f0f0f0;
        }}

        table {{
            width: 100%;
            border-collapse: collapse;
            margin: 1.5rem 0;
        }}

        th,
        td {{
            padding: 0.7rem;
            border: 1px solid #ddd;
            text-align: left;
        }}

        th {{
            font-weight: 600;
            background: #f5f5f5;
        }}

        a {{
            text-decoration: none;
        }}

        img {{
            max-width: 100%;
            height: auto;
        }}
    </style>
</head>

<body>
    {html_body}
</body>
</html>
"""

    return (
        html_document,
        build_export_filename(
            markdown_content,
            "html",
        ),
    )


