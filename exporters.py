"""
Export utilities for the Blog Writing Agent.

This module is responsible for converting the final Markdown
blog generated by the backend into different downloadable
formats.

Supported formats will be added incrementally:

1. Markdown (.md)
2. Plain Text (.txt)
3. HTML (.html)
4. Word (.docx)
5. PDF (.pdf)

The Streamlit frontend should only call these utilities.
File-format conversion logic should remain outside frontend.py.
"""

import re
from io import BytesIO


# ============================================================
# 1. FILENAME UTILITIES
# ============================================================

def sanitize_filename(title: str) -> str:
    """
    Convert a blog title into a safe filename.

    Removes characters that are invalid in Windows filenames
    and performs basic cleanup.
    """

    title = str(title).strip()

    # Characters forbidden by Windows filenames.
    filename = re.sub(
        r'[<>:"/\\|?*]',
        "",
        title,
    )

    # Replace repeated whitespace with a single space.
    filename = re.sub(
        r"\s+",
        " ",
        filename,
    ).strip()

    # Windows does not allow filenames ending in
    # spaces or periods.
    filename = filename.rstrip(
        ". "
    )

    if not filename:
        filename = "blog"

    return filename


# ============================================================
# 2. BLOG TITLE EXTRACTION
# ============================================================

def extract_blog_title(
    markdown_content: str,
) -> str:
    """
    Extract the blog title from the first Markdown H1.

    Example:

        # Building AI Agents with LangGraph

    becomes:

        Building AI Agents with LangGraph

    If no H1 is found, 'blog' is returned.
    """

    if not markdown_content:
        return "blog"

    for line in markdown_content.splitlines():

        line = line.strip()

        if line.startswith("# "):

            title = line[2:].strip()

            if title:
                return title

    return "blog"


# ============================================================
# 3. EXPORT FILENAME
# ============================================================

def build_export_filename(
    markdown_content: str,
    extension: str,
) -> str:
    """
    Build a safe filename for an exported blog.

    Example:

        Building AI Agents with LangGraph.md
        Building AI Agents with LangGraph.pdf
    """

    title = extract_blog_title(
        markdown_content
    )

    safe_title = sanitize_filename(
        title
    )

    extension = (
        str(extension)
        .strip()
        .lstrip(".")
        .lower()
    )

    if not extension:
        raise ValueError(
            "Export extension cannot be empty."
        )

    return (
        f"{safe_title}.{extension}"
    )

# ============================================================
# 4. MARKDOWN EXPORT
# ============================================================

def export_markdown(
    markdown_content: str,
) -> tuple[str, str]:
    """
    Export the blog as Markdown.

    Returns:
        tuple[str, str]:
            - Markdown content
            - Suggested filename
    """

    if not markdown_content or not markdown_content.strip():
        raise ValueError(
            "Markdown content cannot be empty."
        )

    filename = build_export_filename(
        markdown_content,
        "md",
    )

    return (
        markdown_content,
        filename,
    )


# ============================================================
# 5. PLAIN TEXT EXPORT
# ============================================================

def export_text(
    markdown_content: str,
) -> tuple[str, str]:
    """
    Convert the Markdown blog into plain text.

    Markdown formatting such as:
        # headings
        **bold**
        *italic*
        [links](url)
        ```code```

    is removed or simplified so the result can be read
    as normal plain text.
    """

    if not markdown_content or not markdown_content.strip():
        raise ValueError(
            "Markdown content cannot be empty."
        )

    text = markdown_content

    # --------------------------------------------------------
    # Remove fenced code block markers while preserving code.
    # --------------------------------------------------------

    text = re.sub(
        r"```[a-zA-Z0-9_+-]*\n?",
        "",
        text,
    )

    text = text.replace(
        "```",
        "",
    )

    # --------------------------------------------------------
    # Convert Markdown headings to plain text.
    #
    # Example:
    #     ## Introduction
    #
    # becomes:
    #     Introduction
    # --------------------------------------------------------

    text = re.sub(
        r"^\s{0,3}#{1,6}\s+",
        "",
        text,
        flags=re.MULTILINE,
    )

    # --------------------------------------------------------
    # Convert Markdown links.
    #
    # Example:
    #     [LangGraph](https://example.com)
    #
    # becomes:
    #     LangGraph
    # --------------------------------------------------------

    text = re.sub(
        r"\[([^\]]+)\]\([^)]+\)",
        r"\1",
        text,
    )

    # --------------------------------------------------------
    # Remove bold / italic / strikethrough markers.
    # --------------------------------------------------------

    text = re.sub(
        r"\*\*(.*?)\*\*",
        r"\1",
        text,
    )

    text = re.sub(
        r"__(.*?)__",
        r"\1",
        text,
    )

    text = re.sub(
        r"(?<!\*)\*(?!\s)(.*?)(?<!\s)\*(?!\*)",
        r"\1",
        text,
    )

    text = re.sub(
        r"(?<!_)_(?!\s)(.*?)(?<!\s)_(?!_)",
        r"\1",
        text,
    )

    text = re.sub(
        r"~~(.*?)~~",
        r"\1",
        text,
    )

    # --------------------------------------------------------
    # Remove inline code markers.
    #
    # Example:
    #     `StateGraph`
    #
    # becomes:
    #     StateGraph
    # --------------------------------------------------------

    text = re.sub(
        r"`([^`]+)`",
        r"\1",
        text,
    )

    # --------------------------------------------------------
    # Remove blockquote markers.
    # --------------------------------------------------------

    text = re.sub(
        r"^\s*>\s?",
        "",
        text,
        flags=re.MULTILINE,
    )

    # --------------------------------------------------------
    # Convert unordered Markdown bullets into simple bullets.
    # --------------------------------------------------------

    text = re.sub(
        r"^\s*[-*+]\s+",
        "• ",
        text,
        flags=re.MULTILINE,
    )

    # --------------------------------------------------------
    # Remove ordered-list Markdown formatting.
    #
    # Keep the numbers because they are useful in plain text.
    # --------------------------------------------------------

    text = re.sub(
        r"^\s*(\d+)\.\s+",
        r"\1. ",
        text,
        flags=re.MULTILINE,
    )

    # --------------------------------------------------------
    # Remove excessive horizontal-rule formatting.
    # --------------------------------------------------------

    text = re.sub(
        r"^\s*([-*_])(?:\s*\1){2,}\s*$",
        "",
        text,
        flags=re.MULTILINE,
    )

    # --------------------------------------------------------
    # Normalize excessive blank lines.
    # --------------------------------------------------------

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text,
    )

    return (
        text.strip() + "\n",
        build_export_filename(
            markdown_content,
            "txt",
        ),
    )


