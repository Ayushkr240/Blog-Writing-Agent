# 7. DOCX EXPORT
# ============================================================

def export_docx(
    markdown_content: str,
) -> tuple[bytes, str]:
    """
    Convert the Markdown blog into a Microsoft Word document.

    Returns:
        tuple[bytes, str]:
            - DOCX file as bytes
            - Suggested filename
    """

    if not markdown_content or not markdown_content.strip():
        raise ValueError(
            "Markdown content cannot be empty."
        )

    try:
        from io import BytesIO

        from docx import Document
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.enum.style import WD_STYLE_TYPE
        from docx.shared import Inches, Pt

    except ImportError as exc:
        raise ImportError(
            "The 'python-docx' package is required "
            "for DOCX export. Install it with: "
            "pip install python-docx"
        ) from exc

    # --------------------------------------------------------
    # Create document
    # --------------------------------------------------------

    document = Document()

    # --------------------------------------------------------
    # Page setup
    # --------------------------------------------------------

    section = document.sections[0]

    section.top_margin = Inches(0.8)
    section.bottom_margin = Inches(0.8)
    section.left_margin = Inches(0.85)
    section.right_margin = Inches(0.85)

    # --------------------------------------------------------
    # Normal paragraph style
    # --------------------------------------------------------

    normal_style = document.styles["Normal"]

    normal_style.font.name = "Aptos"
    normal_style.font.size = Pt(11)

    # --------------------------------------------------------
    # Create a code style
    # --------------------------------------------------------

    if "Blog Code" not in [
        style.name for style in document.styles
    ]:

        code_style = document.styles.add_style(
            "Blog Code",
            WD_STYLE_TYPE.PARAGRAPH,
        )

        code_style.font.name = "Consolas"
        code_style.font.size = Pt(9)

    # --------------------------------------------------------
    # Helper: add inline formatted text
    # --------------------------------------------------------

    def add_inline_text(
        paragraph,
        text: str,
    ):
        """
        Add a Markdown paragraph while preserving
        basic inline formatting:

            **bold**
            *italic*
            `code`
        """

        pattern = re.compile(
            r"(\*\*.*?\*\*|__.*?__|`.*?`|\*.*?\*|_.*?_)"
        )

        parts = pattern.split(text)

        for part in parts:

            if not part:
                continue

            # Bold
            if (
                part.startswith("**")
                and part.endswith("**")
            ) or (
                part.startswith("__")
                and part.endswith("__")
            ):

                run = paragraph.add_run(
                    part[2:-2]
                )

                run.bold = True

            # Inline code
            elif (
                part.startswith("`")
                and part.endswith("`")
            ):

                run = paragraph.add_run(
                    part[1:-1]
                )

                run.font.name = "Consolas"
                run.font.size = Pt(9)

            # Italic
            elif (
                part.startswith("*")
                and part.endswith("*")
            ) or (
                part.startswith("_")
                and part.endswith("_")
            ):

                run = paragraph.add_run(
                    part[1:-1]
                )

                run.italic = True

            else:

                paragraph.add_run(part)

    # --------------------------------------------------------
    # Process Markdown line-by-line
    # --------------------------------------------------------

    lines = markdown_content.splitlines()

    inside_code_block = False
    code_lines = []

    for line in lines:

        stripped = line.strip()

        # ----------------------------------------------------
        # Fenced code block
        # ----------------------------------------------------

        if stripped.startswith("```"):

            if not inside_code_block:

                inside_code_block = True
                code_lines = []

            else:

                inside_code_block = False

                code_paragraph = document.add_paragraph(
                    style="Blog Code"
                )

                code_paragraph.paragraph_format.space_before = Pt(6)
                code_paragraph.paragraph_format.space_after = Pt(6)

                code_paragraph.add_run(
                    "\n".join(code_lines)
                )

                code_lines = []

            continue

        if inside_code_block:

            code_lines.append(line)

            continue

        # ----------------------------------------------------
        # Empty line
        # ----------------------------------------------------

        if not stripped:

            continue

        # ----------------------------------------------------
        # Heading 1
        # ----------------------------------------------------

        if re.match(
            r"^#\s+",
            stripped,
        ):

            heading_text = re.sub(
                r"^#\s+",
                "",
                stripped,
            )

            paragraph = document.add_heading(
                heading_text,
                level=1,
            )

            paragraph.alignment = (
                WD_ALIGN_PARAGRAPH.LEFT
            )

            continue

        # ----------------------------------------------------
        # Heading 2
        # ----------------------------------------------------

        if re.match(
            r"^##\s+",
            stripped,
        ):

            heading_text = re.sub(
                r"^##\s+",
                "",
                stripped,
            )

            document.add_heading(
                heading_text,
                level=2,
            )

            continue

        # ----------------------------------------------------
        # Heading 3
        # ----------------------------------------------------

        if re.match(
            r"^###\s+",
            stripped,
        ):

            heading_text = re.sub(
                r"^###\s+",
                "",
                stripped,
            )

            document.add_heading(
                heading_text,
                level=3,
            )

            continue

        # ----------------------------------------------------
        # Heading 4–6
        # ----------------------------------------------------

        heading_match = re.match(
            r"^(#{4,6})\s+(.+)",
            stripped,
        )

        if heading_match:

            level = min(
                len(heading_match.group(1)),
                6,
            )

            document.add_heading(
                heading_match.group(2),
                level=level,
            )

            continue

        # ----------------------------------------------------
        # Unordered list
        # ----------------------------------------------------

        bullet_match = re.match(
            r"^[-*+]\s+(.+)",
            stripped,
        )

        if bullet_match:

            paragraph = document.add_paragraph(
                style="List Bullet"
            )

            add_inline_text(
                paragraph,
                bullet_match.group(1),
            )

            continue

        # ----------------------------------------------------
        # Ordered list
        # ----------------------------------------------------

        numbered_match = re.match(
            r"^\d+\.\s+(.+)",
            stripped,
        )

        if numbered_match:

            paragraph = document.add_paragraph(
                style="List Number"
            )

            add_inline_text(
                paragraph,
                numbered_match.group(1),
            )

            continue

        # ----------------------------------------------------
        # Blockquote
        # ----------------------------------------------------

        quote_match = re.match(
            r"^>\s?(.*)",
            stripped,
        )

        if quote_match:

            paragraph = document.add_paragraph()

            paragraph.paragraph_format.left_indent = (
                Inches(0.3)
            )

            run = paragraph.add_run(
                quote_match.group(1)
            )

            run.italic = True

            continue

        # ----------------------------------------------------
        # Horizontal rule
        # ----------------------------------------------------

        if re.match(
            r"^([-*_])(?:\s*\1){2,}$",
            stripped,
        ):

            paragraph = document.add_paragraph()

            paragraph.add_run(
                "────────────────────────"
            )

            continue

        # ----------------------------------------------------
        # Normal paragraph
        # ----------------------------------------------------

        paragraph = document.add_paragraph()

        paragraph.paragraph_format.space_after = Pt(8)
        paragraph.paragraph_format.line_spacing = 1.15

        add_inline_text(
            paragraph,
            stripped,
        )

    # --------------------------------------------------------
    # Save document into memory
    # --------------------------------------------------------

    buffer = BytesIO()

    document.save(buffer)

    buffer.seek(0)

    filename = build_export_filename(
        markdown_content,
        "docx",
    )

    return (
        buffer.getvalue(),
        filename,
    )

